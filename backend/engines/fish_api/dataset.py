"""Fish story renders read back as a speech-training corpus.

Everything here reads the run folders the story board already wrote
(``<root>/<chapter>/<story>/run-NNN_<time>_<id>/manifest.json`` + ``story.json`` + the audio)
and, on an explicit export, writes a new folder. Nothing contacts Fish or any network.

The corpus is *synthetic* speech: every clip was generated by Fish Audio. Whether it may be
used to train another model is governed by Fish's terms, not by this app; the export card
records the source so that can be checked later.
"""
from __future__ import annotations

import collections
import csv
import glob
import hashlib
import json
import logging
import os
import re
import shutil
import statistics
import threading
from typing import Iterable, Optional

logger = logging.getLogger("omnivoice.fish.dataset")

ROOT_KEY = "tts.fish.dataset_dir"
IGNORED_DIRS = {"fish_non_api"}  # hand-made / non-API material the owner keeps beside the API runs
TAG_RE = re.compile(r"\[[^\[\]\n]{1,40}\]")
_SPACE_RE = re.compile(r"\s+")
_SLUG_RE = re.compile(r"[^A-Za-z0-9]+")

_lock = threading.Lock()
_cache: dict[str, tuple[tuple, "Corpus"]] = {}


# ── root setting ──
def get_root() -> Optional[str]:
    from services import settings_store

    return settings_store.get_text(ROOT_KEY) or None


def set_root(path: Optional[str]) -> Optional[str]:
    """Remember the folder holding the chapter folders. It is only ever read, never created."""
    from services import settings_store

    raw = (path or "").strip().strip('"')
    if not raw:
        settings_store.clear_text(ROOT_KEY)
        return None
    if len(raw) > 400 or "\x00" in raw or not os.path.isabs(raw):
        raise ValueError("Enter the full path of the folder that holds your chapter folders.")
    full = os.path.normpath(raw)
    if not os.path.isdir(full):
        raise ValueError("That folder does not exist.")
    settings_store.set_text(ROOT_KEY, full)
    return full


# ── text helpers ──
def normalize_tags(names: Optional[Iterable[str]]) -> dict[str, str]:
    """Tags to keep, as ``{tag as written in the data: tag to write}``.

    ``"[Laughter], sigh"`` keeps both as they are. ``"laughing=laughter"`` keeps ``[laughing]`` but
    writes it as ``[laughter]``, for a model that spells the same sound differently.
    """
    out: dict[str, str] = {}
    for name in names or ():
        for part in str(name).split(","):
            source, _, target = part.partition("=")
            source = source.strip().strip("[]").strip().lower()[:40]
            target = target.strip().strip("[]").strip().lower()[:40] or source
            if source:
                out[source] = target
    return out


def strip_tags(text: str, keep: Optional[Iterable[str]] = None) -> str:
    """Plain speech text: inline ``[emotion]`` / ``[break]`` tags removed, spaces tidied.

    Tags named in ``keep`` stay (renamed if given as ``name=other``); every other tag is dropped.
    """
    kept = keep if isinstance(keep, dict) else normalize_tags(keep)
    if kept:
        def one(m):
            name = m.group(0)[1:-1].strip().lower()
            if name not in kept:
                return " "
            return m.group(0) if kept[name] == name else f"[{kept[name]}]"

        text = TAG_RE.sub(one, text or "")
    else:
        text = TAG_RE.sub(" ", text or "")
    return _SPACE_RE.sub(" ", text).strip()


def tags_of(text: str) -> list[str]:
    return [t[1:-1].strip().lower() for t in TAG_RE.findall(text or "")]


def slug(name: str, fallback: str = "speaker") -> str:
    return _SLUG_RE.sub("_", name or "").strip("_")[:40] or fallback


# ── scanning ──
class Corpus:
    def __init__(self, root: str, lines: list[dict], runs: list[dict]):
        self.root = root
        self.lines = lines
        self.runs = runs
        self.by_key = {line["key"]: line for line in lines}

    def speakers(self) -> list[dict]:
        groups: dict[str, list[dict]] = collections.defaultdict(list)
        for line in self.lines:
            groups[line["voice_id"]].append(line)
        out = []
        for voice_id, rows in groups.items():
            names = collections.Counter(r["voice_name"] for r in rows)
            usable = [r for r in rows if not r["duplicate"]]
            seconds = sum(r["duration_s"] for r in usable)
            tag_counts = collections.Counter(t for r in usable for t in r["tags"])
            out.append({
                "voice_id": voice_id,
                "name": names.most_common(1)[0][0],
                "aliases": [n for n in names if n != names.most_common(1)[0][0]],
                "lines": len(usable),
                "duplicates": len(rows) - len(usable),
                "seconds": round(seconds, 1),
                "avg_s": round(seconds / len(usable), 2) if usable else 0,
                "chapters": len({r["chapter"] for r in usable}),
                "top_tags": tag_counts.most_common(6),
            })
        out.sort(key=lambda s: -s["seconds"])
        return out


def _read_json(path: str) -> Optional[dict]:
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


def _manifests(root: str) -> list[str]:
    found = []
    for pattern in ("*/*/run-*/manifest.json", "*/run-*/manifest.json"):
        for path in glob.glob(os.path.join(glob.escape(root), pattern)):
            rel = os.path.relpath(path, root).split(os.sep)
            if rel[0] in IGNORED_DIRS:
                continue
            found.append(path)
    return sorted(set(found))


def _signature(paths: Iterable[str]) -> tuple:
    sig = []
    for p in paths:
        try:
            sig.append((p, os.path.getmtime(p)))
        except OSError:
            continue
    return tuple(sig)


def _scan(root: str, manifests: list[str]) -> Corpus:
    lines: list[dict] = []
    runs: list[dict] = []
    for path in manifests:
        run_dir = os.path.dirname(path)
        man = _read_json(path)
        if not man or not man.get("chunks"):
            continue
        story = (_read_json(os.path.join(run_dir, "story.json")) or {}).get("draft", {})
        story_text = {c.get("id"): c.get("text", "") for c in story.get("chunks", [])}
        rel_run = os.path.relpath(run_dir, root)
        chapter = rel_run.split(os.sep)[0]
        run_id = str(man.get("id") or os.path.basename(run_dir))
        done = failed = missing = 0
        for chunk in man["chunks"]:
            if chunk.get("status") != "done" or not chunk.get("file"):
                failed += 1
                continue
            audio = os.path.join(run_dir, chunk["file"])
            if not os.path.isfile(audio):
                missing += 1
                continue
            raw = chunk.get("text") or story_text.get(chunk.get("id"), "")
            plain = strip_tags(raw)
            if not plain or not chunk.get("duration_s"):
                continue
            done += 1
            lines.append({
                "key": f"{run_id}:{chunk['id']}",
                "run_id": run_id,
                "chapter": chapter,
                "run": os.path.basename(run_dir),
                "index": chunk.get("index") or 0,
                "file": os.path.relpath(audio, root).replace(os.sep, "/"),
                "voice_id": chunk.get("voice") or man.get("settings", {}).get("reference_id") or "unknown",
                "voice_name": chunk.get("voice_name") or "narrator",
                "text": raw,
                "plain": plain,
                "tags": tags_of(raw),
                "words": len(plain.split()),
                "duration_s": float(chunk["duration_s"]),
                "sample_rate": chunk.get("sample_rate") or man.get("sample_rate"),
                "sha256": chunk.get("sha256"),
                "model": man.get("model"),
                "started_at": man.get("started_at") or 0,
                "duplicate": False,
            })
        runs.append({"run_id": run_id, "chapter": chapter, "run": os.path.basename(run_dir),
                     "started_at": man.get("started_at") or 0, "model": man.get("model"),
                     "lines": done, "failed": failed, "missing": missing})
    # The same words by the same voice rendered again (a re-run): only the newest copy counts.
    newest: dict[tuple, dict] = {}
    for line in sorted(lines, key=lambda l: (l["started_at"], l["index"])):
        newest_key = (line["voice_id"], line["plain"])
        previous = newest.get(newest_key)
        if previous:
            previous["duplicate"] = True
        newest[newest_key] = line
    lines.sort(key=lambda l: (l["chapter"], l["started_at"], l["index"]))
    return Corpus(root, lines, runs)


def load(root: Optional[str] = None, *, refresh: bool = False) -> Optional[Corpus]:
    """The indexed corpus for ``root`` (default: the saved folder). Cached until a manifest changes."""
    root = root or get_root()
    if not root or not os.path.isdir(root):
        return None
    root = os.path.normpath(root)
    manifests = _manifests(root)
    sig = _signature(manifests)
    with _lock:
        hit = _cache.get(root)
        if hit and hit[0] == sig and not refresh:
            return hit[1]
    corpus = _scan(root, manifests)
    with _lock:
        _cache[root] = (sig, corpus)
    return corpus


def audio_path(corpus: Corpus, key: str) -> Optional[str]:
    """Absolute path of one indexed clip; only files the index itself lists can be served."""
    line = corpus.by_key.get(key)
    if not line:
        return None
    path = os.path.normpath(os.path.join(corpus.root, line["file"]))
    return path if os.path.isfile(path) and os.path.commonpath([corpus.root, path]) == corpus.root else None


# ── selecting ──
_QUALITY = (  # filter key -> (stat, comparison)
    ("max_peak", "peak", "max"), ("min_peak", "peak", "min"),
    ("max_clip", "clip", "max"), ("min_rms_db", "rms_db", "min"), ("max_rms_db", "rms_db", "max"),
    ("max_lead_ms", "lead_ms", "max"), ("max_tail_ms", "tail_ms", "max"),
    ("max_pauses", "pauses", "max"), ("max_gap_ms", "max_gap_ms", "max"),
)
SORTS = ("order", "duration_desc", "duration_asc", "words_desc", "words_asc", "random")


def select(corpus: Corpus, f: dict) -> list[dict]:
    """Lines matching a filter dict. Shared by the browser and the exporter so they agree.

    Tags: ``tags_any`` (at least one), ``tags_all`` (every one), ``tags_none`` (none of them).
    Quality limits need the clip analysed first; while one is set, un-analysed clips are left out.
    """
    from . import dataset_quality

    voices = set(f.get("voice_ids") or [])
    chapters = set(f.get("chapters") or [])
    exclude = set(f.get("exclude_keys") or [])
    only = set(f["only_keys"]) if f.get("only_keys") is not None else None
    query = (f.get("q") or "").strip().lower()
    tags_all = set(normalize_tags(f.get("tags_all"))) | ({f["tag"].strip().lower()} if (f.get("tag") or "").strip() else set())
    tags_any = set(normalize_tags(f.get("tags_any")))
    tags_none = set(normalize_tags(f.get("tags_none")))
    min_d, max_d = f.get("min_dur"), f.get("max_dur")
    min_w, max_w = f.get("min_words"), f.get("max_words")
    dups = bool(f.get("duplicates", False))
    limits = [(key, stat, how, f[key]) for key, stat, how in _QUALITY if f.get(key) is not None]
    out = []
    for line in corpus.lines:
        if voices and line["voice_id"] not in voices:
            continue
        if chapters and line["chapter"] not in chapters:
            continue
        if line["duplicate"] and not dups:
            continue
        if line["key"] in exclude:
            continue
        if only is not None and line["key"] not in only:
            continue
        if min_d is not None and line["duration_s"] < min_d:
            continue
        if max_d is not None and line["duration_s"] > max_d:
            continue
        if min_w is not None and line["words"] < min_w:
            continue
        if max_w is not None and line["words"] > max_w:
            continue
        have = set(line["tags"])
        if tags_all and not tags_all <= have:
            continue
        if tags_any and not tags_any & have:
            continue
        if tags_none and tags_none & have:
            continue
        if query and query not in line["plain"].lower():
            continue
        if limits:
            stats = dataset_quality.get(line)
            if stats is None or any(
                (stats[stat] > value) if how == "max" else (stats[stat] < value)
                for _, stat, how, value in limits
            ):
                continue
        out.append(line)
    return _sorted(out, f.get("sort") or "order", int(f.get("seed") or 0))


def _sorted(lines: list[dict], how: str, seed: int) -> list[dict]:
    if how == "duration_desc":
        return sorted(lines, key=lambda l: -l["duration_s"])
    if how == "duration_asc":
        return sorted(lines, key=lambda l: l["duration_s"])
    if how == "words_desc":
        return sorted(lines, key=lambda l: -l["words"])
    if how == "words_asc":
        return sorted(lines, key=lambda l: l["words"])
    if how == "random":
        import random

        shuffled = list(lines)
        random.Random(seed).shuffle(shuffled)
        return shuffled
    return lines


DURATION_EDGES = (0, 1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 30)


def facets(lines: list[dict]) -> dict:
    """What the current selection looks like: lengths, tags, chapters and audio quality."""
    import collections

    from . import dataset_quality

    edges = DURATION_EDGES
    counts = [0] * len(edges)
    for l in lines:
        d = l["duration_s"]
        counts[max(i for i, e in enumerate(edges) if d >= e)] += 1
    bins = [{"from": e, "to": edges[i + 1] if i + 1 < len(edges) else None, "clips": counts[i]}
            for i, e in enumerate(edges)]
    tag_counts = collections.Counter(t for l in lines for t in set(l["tags"]))
    per_chapter: dict[str, list] = {}
    levels: dict[str, list] = collections.defaultdict(list)
    peaks: dict[str, float] = {}
    measured = [(l, dataset_quality.get(l)) for l in lines]
    for l, st in measured:
        c = per_chapter.setdefault(l["chapter"], [0, 0.0])
        c[0] += 1
        c[1] += l["duration_s"]
        if st:
            levels[l["chapter"]].append(st["rms_db"])
            peaks[l["chapter"]] = max(peaks.get(l["chapter"], 0.0), st["peak"])
    have = [st for _, st in measured if st]
    quality = {
        "analyzed": len(have), "total": len(lines),
        "clipping": sum(1 for st in have if st["clip"] > 0.0005 or st["peak"] >= 0.999),
        "loud": sum(1 for st in have if st["peak"] > 0.8),
        "quiet": sum(1 for st in have if st["peak"] < 0.1),
        "choppy": sum(1 for st in have if st["pauses"] >= 3),
        "long_edges": sum(1 for st in have if st["lead_ms"] > 500 or st["tail_ms"] > 800),
    }
    words = [l["words"] for l in lines]
    return {
        "clips": len(lines), "seconds": round(sum(l["duration_s"] for l in lines), 1),
        "duration": bins,
        "tags": tag_counts.most_common(80),
        "chapters": [{"chapter": c, "clips": n, "seconds": round(sec, 1),
                      "rms_db": round(statistics.median(levels[c]), 1) if levels.get(c) else None,
                      "peak": peaks.get(c)}
                     for c, (n, sec) in sorted(per_chapter.items())],
        "words": {"min": min(words), "max": max(words), "avg": round(sum(words) / len(words), 1)} if words else None,
        "quality": quality,
    }


# ── export ──
FORMATS = ("jsonl", "ljspeech", "fish_lab")


def _in_validation(sha: str, fraction: float) -> bool:
    """A stable split: the same clip always lands on the same side, whatever else is selected."""
    return fraction > 0 and int(hashlib.sha256((sha or "").encode()).hexdigest()[:8], 16) / 0xFFFFFFFF < fraction


def export(corpus: Corpus, f: dict, dest: str, *, formats: list[str], text_mode: str = "keep",
           sample_rate: Optional[int] = None, val_fraction: float = 0.0, name: str = "fish-dataset",
           keep_tags: Optional[list[str]] = None) -> dict:
    """Write the selected clips under ``dest/<name>/<speaker>/`` plus metadata. Never overwrites."""
    import numpy as np
    import soundfile as sf

    bad = [x for x in formats if x not in FORMATS]
    if bad or not formats:
        raise ValueError(f"Pick at least one format of: {', '.join(FORMATS)}.")
    if text_mode not in ("keep", "strip"):
        raise ValueError("text_mode must be keep or strip.")
    if sample_rate is not None and not 8000 <= sample_rate <= 96000:
        raise ValueError("sample_rate must be between 8000 and 96000.")
    if not 0 <= val_fraction < 0.5:
        raise ValueError("val_fraction must be between 0 and 0.5.")
    kept = normalize_tags(keep_tags)
    if len(kept) > 100:
        raise ValueError("Keep at most 100 tags.")
    lines = select(corpus, {**f, "sort": "order"})
    if not lines:
        raise ValueError("Nothing matches the current filters.")
    raw = (dest or "").strip().strip('"')
    if not raw or not os.path.isabs(raw):
        raise ValueError("Enter the full path of the folder to export into.")
    out_dir = os.path.join(os.path.normpath(raw), slug(name, "fish-dataset"))
    if os.path.exists(out_dir) and os.listdir(out_dir):
        raise ValueError("That export folder already has files. Choose a new name or folder.")
    os.makedirs(out_dir, exist_ok=True)

    names: dict[str, str] = {}
    for sp in corpus.speakers():
        base = slug(sp["name"])
        while base in names.values():
            base = f"{base}_{sp['voice_id'][:4]}"
        names[sp["voice_id"]] = base
    counters: collections.Counter = collections.Counter()
    rows: list[dict] = []
    csv_rows: dict[str, list[list[str]]] = collections.defaultdict(list)
    seconds = 0.0
    for line in lines:
        speaker = names[line["voice_id"]]
        counters[speaker] += 1
        clip_id = f"{speaker}_{counters[speaker]:05d}"
        folder = os.path.join(out_dir, speaker)
        os.makedirs(folder, exist_ok=True)
        src = os.path.join(corpus.root, line["file"])
        target = os.path.join(folder, clip_id + ".wav")
        duration = line["duration_s"]
        rate = line["sample_rate"]
        if sample_rate and sample_rate != line["sample_rate"]:
            from .story_jobs import _resample

            data, src_rate = sf.read(src, dtype="float32", always_2d=True)
            data = _resample(data.mean(axis=1, keepdims=True) if data.shape[1] > 1 else data, src_rate, sample_rate)
            sf.write(target, np.clip(data, -1.0, 1.0), sample_rate, subtype="PCM_16")
            rate, duration = sample_rate, len(data) / sample_rate
        else:
            shutil.copyfile(src, target)
        text = strip_tags(line["text"], kept) if text_mode == "strip" else line["text"].strip()
        seconds += duration
        rows.append({
            "file_name": f"{speaker}/{clip_id}.wav", "text": text, "text_raw": line["text"].strip(),
            "text_plain": line["plain"], "speaker": speaker, "speaker_name": line["voice_name"],
            "voice_id": line["voice_id"], "duration": round(duration, 3), "sample_rate": rate,
            "tags": line["tags"], "chapter": line["chapter"], "run_id": line["run_id"],
            "validation": _in_validation(line["sha256"] or clip_id, val_fraction),
        })
        if "fish_lab" in formats:
            with open(os.path.join(folder, clip_id + ".lab"), "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text + "\n")
        csv_rows[speaker].append([clip_id, text.replace("|", " "), line["plain"].replace("|", " ")])

    if "jsonl" in formats:
        def write(path: str, subset: list[dict]) -> None:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                for row in subset:
                    fh.write(json.dumps({k: v for k, v in row.items() if k != "validation"}, ensure_ascii=False) + "\n")

        write(os.path.join(out_dir, "metadata.jsonl"), rows)
        if val_fraction > 0:
            write(os.path.join(out_dir, "train.jsonl"), [r for r in rows if not r["validation"]])
            write(os.path.join(out_dir, "val.jsonl"), [r for r in rows if r["validation"]])
    if "ljspeech" in formats:
        for speaker, items in csv_rows.items():
            with open(os.path.join(out_dir, speaker, "metadata.csv"), "w", encoding="utf-8", newline="") as fh:
                csv.writer(fh, delimiter="|", quoting=csv.QUOTE_NONE, escapechar="\\").writerows(items)
    per_speaker = {s: {"clips": c, "seconds": round(sum(r["duration"] for r in rows if r["speaker"] == s), 1)}
                   for s, c in counters.items()}
    card = {
        "name": name, "clips": len(rows), "hours": round(seconds / 3600, 3), "speakers": per_speaker,
        "formats": formats, "text_mode": text_mode, "kept_tags": kept if text_mode == "strip" else {}, "sample_rate": sample_rate or "as rendered",
        "val_fraction": val_fraction, "source_root": corpus.root,
        "source": "Synthetic speech generated by Fish Audio (models: "
                  + ", ".join(sorted({l["model"] or "unknown" for l in lines}))
                  + "). Check Fish's terms before using it to train another model.",
        "filters": {k: v for k, v in f.items() if k != "exclude_keys"} | {"excluded": len(f.get("exclude_keys") or [])},
    }
    with open(os.path.join(out_dir, "dataset.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(card, fh, ensure_ascii=False, indent=2)
    return {**card, "path": out_dir}
