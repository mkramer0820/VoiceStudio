FORMATS = ("jsonl", "ljspeech", "fish_lab", "omnivoice", "qwen3_tts")
OMNIVOICE_RATE = 24000  # what OmniVoice's audio tokenizer reads
OMNIVOICE_TAGS = (  # non-verbal tags OmniVoice understands (omnivoice.models.omnivoice._NONVERBAL_PATTERN)
    "laughter", "sigh", "confirmation-en", "question-en", "question-ah", "question-oh", "question-ei",
    "question-yi", "surprise-ah", "surprise-oh", "surprise-wa", "surprise-yo", "dissatisfaction-hnn",
)
PEAK_CEILING = 0.97  # loudness matching never pushes a clip's peak above this


def resample_mono(data, src: int, dst: int):
    """(n,) or (n, channels) float32 to mono float32 at ``dst`` Hz, band-limited when SciPy is present."""
    import numpy as np

    mono = data.mean(axis=1) if data.ndim > 1 else data
    if src == dst:
        return mono.astype("float32")
    try:
        from math import gcd

        from scipy.signal import resample_poly

        g = gcd(int(src), int(dst))
        return resample_poly(mono, int(dst) // g, int(src) // g).astype("float32")
    except Exception:  # noqa: BLE001 — SciPy missing: fall back to the story join's resampler
        from .story_jobs import _resample

        return _resample(mono.reshape(-1, 1), src, dst)[:, 0]


def loudness_gain(data, target_db: float) -> tuple[float, bool]:
    """Linear gain that brings a clip's whole-clip RMS to ``target_db`` dBFS (the number
    ``dataset_quality.measure`` reports as ``rms_db``), capped so the peak stays under
    ``PEAK_CEILING``. Returns ``(gain, peak_limited)``."""
    import numpy as np

    rms = float(np.sqrt(np.mean(data ** 2)))
    peak = float(np.abs(data).max()) if len(data) else 0.0
    if rms <= 1e-6 or peak <= 0:
        return 1.0, False
    gain = 10 ** ((target_db - 20 * math.log10(rms)) / 20)
    if peak * gain > PEAK_CEILING:
        return PEAK_CEILING / peak, True
    return gain, False


def rms_db(data) -> float:
    """Whole-clip RMS in dBFS, the same number ``dataset_quality.measure`` reports as ``rms_db``."""
    import numpy as np

    return 20 * math.log10(float(np.sqrt(np.mean(data ** 2))) + 1e-9) if len(data) else -180.0


def apply_loudness(mono, target_db: float):
    """``mono`` brought to ``target_db`` (peak capped). Returns the new samples and what happened:
    level before and after, the gain in dB and whether the peak cap kept it from reaching the target."""
    import numpy as np

    before = rms_db(mono)
    gain, limited = loudness_gain(mono, target_db)
    out = np.clip(mono * gain, -1.0, 1.0)
    return out, {"before_db": before, "after_db": rms_db(out) if gain != 1.0 or limited else before,
                 "gain_db": 20 * math.log10(gain) if gain > 0 else 0.0, "peak_limited": limited}


class LevelReport:
    """Collects what level matching did to each clip and sums it up per chapter for the export report."""

    MIN_GAIN_DB = 0.05  # a smaller change does not count as "adjusted"

    def __init__(self, target_db: float):
        self.target = target_db
        self._rows: list[tuple[str, dict]] = []

    def add(self, chapter: str, info: dict) -> None:
        self._rows.append((chapter, info))

    def chapter_levels(self, key: str) -> dict[str, float]:
        by: dict[str, list[float]] = collections.defaultdict(list)
        for chapter, info in self._rows:
            by[chapter].append(info[key])
        return {c: round(statistics.median(v), 1) for c, v in sorted(by.items())}

    def summary(self) -> dict:
        def shortfall(info: dict) -> float:
            return max(0.0, self.target - info["after_db"]) if info["peak_limited"] else 0.0

        chapters: dict[str, dict] = {}
        for chapter, info in self._rows:
            c = chapters.setdefault(chapter, {"clips": 0, "adjusted": 0, "peak_limited": 0, "worst_shortfall_db": 0.0})
            c["clips"] += 1
            c["adjusted"] += int(abs(info["gain_db"]) >= self.MIN_GAIN_DB)
            c["peak_limited"] += int(info["peak_limited"])
            c["worst_shortfall_db"] = max(c["worst_shortfall_db"], round(shortfall(info), 1))
        before, after = self.chapter_levels("before_db"), self.chapter_levels("after_db")
        for chapter, c in chapters.items():
            c["median_before_db"], c["median_after_db"] = before[chapter], after[chapter]
        return {
            "target_rms_db": self.target, "clips": len(self._rows),
            "adjusted": sum(c["adjusted"] for c in chapters.values()),
            "peak_limited": sum(c["peak_limited"] for c in chapters.values()),
            "worst_shortfall_db": max((c["worst_shortfall_db"] for c in chapters.values()), default=0.0),
            "chapters": dict(sorted(chapters.items())),
        }


def level_summary(lines: list[dict]) -> dict:
    """Min, median and max measured clip level of ``lines`` plus a count per 0.1 dB, so the export dialog can
    say how many clips sit above or below a chosen target. Clips not measured yet are only counted."""
    from . import dataset_quality

    levels = [st["rms_db"] for st in (dataset_quality.get(l) for l in lines) if st]
    counts = collections.Counter(levels)
    return {"measured": len(levels), "total": len(lines),
            "min": min(levels) if levels else None, "max": max(levels) if levels else None,
            "median": round(statistics.median(levels), 1) if levels else None,
            "counts": sorted(counts.items())}


def _in_validation(sha: str, fraction: float) -> bool:
    """A stable split: the same clip always lands on the same side, whatever else is selected."""
    return fraction > 0 and int(hashlib.sha256((sha or "").encode()).hexdigest()[:8], 16) / 0xFFFFFFFF < fraction


def export(corpus: Corpus, f: dict, dest: str, *, formats: list[str], text_mode: str = "keep",
           sample_rate: Optional[int] = None, val_fraction: float = 0.0, name: str = "fish-dataset",
           keep_tags: Optional[list[str]] = None, loudness_db: Optional[float] = None,
           language_id: str = "en", strict_tags: bool = True, training: Optional[dict] = None,
           qwen3: Optional[dict] = None) -> dict:
    """Write the selected clips under ``dest/<name>/<speaker>/`` plus metadata. Never overwrites."""
    import numpy as np
    import soundfile as sf

    bad = [x for x in formats if x not in FORMATS]
    if bad or not formats:
        raise ValueError(f"Pick at least one format of: {', '.join(FORMATS)}.")
    if text_mode not in ("keep", "strip"):
        raise ValueError("text_mode must be keep or strip.")
    if sample_rate is not None and not 8000 <= sample_rate <= 96000:
        raise ValueError("sample_rate must be between 8000 and 96000.")
    if not 0 <= val_fraction < 0.5:
        raise ValueError("val_fraction must be between 0 and 0.5.")
    if loudness_db is not None and not -60.0 <= loudness_db <= -3.0:
        raise ValueError("loudness_db must be between -60 and -3 (dBFS RMS).")
    if "qwen3_tts" in formats:
        # A folder of its own (one speaker, Qwen's layout): text is always plain speech, audio always 24 kHz.
        from . import qwen3_export

        if formats != ["qwen3_tts"]:
            raise ValueError("The qwen3_tts format writes a complete folder of its own; untick the other formats.")
        if sample_rate not in (None, qwen3_export.RATE):
            raise ValueError(f"The qwen3_tts format is always {qwen3_export.RATE} Hz; leave the sample rate unset.")
        if val_fraction:
            raise ValueError("The official Qwen3-TTS scripts have no validation input; leave the validation share at 0.")
        from . import qwen3_colab

        # ``training`` is the same Training setup field the omnivoice format uses, read with Qwen's own settings.
        return qwen3_export.export(corpus, f, dest, name=name, loudness_db=loudness_db,
                                   options=qwen3_export.options_from(qwen3), settings=qwen3_colab.settings_from(training))
    kept = normalize_tags(keep_tags)
    if len(kept) > 100:
        raise ValueError("Keep at most 100 tags.")
    omni = "omnivoice" in formats
    if omni:
        if sample_rate not in (None, OMNIVOICE_RATE):
            raise ValueError(f"The omnivoice format is always {OMNIVOICE_RATE} Hz; leave the sample rate unset.")
        sample_rate = OMNIVOICE_RATE
        text_mode = "strip"  # OmniVoice reads plain text plus its own tags, never Fish's [slow] / [calm]
        unknown = sorted({render_tag(t) for t in kept.values() if t not in OMNIVOICE_TAGS})
        if unknown and strict_tags:
            raise ValueError("OmniVoice does not know the tag(s) " + ", ".join(unknown)
                             + ". Convert them to one of: " + ", ".join(OMNIVOICE_TAGS) + ", leave them out, "
                             "or untick 'only tags OmniVoice knows' to write your own.")
        language_id = (language_id or "en").strip()
        if not re.fullmatch(r"[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})?", language_id):
            raise ValueError("language_id must look like en, de or pt-BR.")
    train_options = None
    if training is not None:
        if not omni:
            raise ValueError("A training configuration is written with the omnivoice format only.")
        from . import training_bundle

        train_options = training_bundle.options_from(training)
    lines = select(corpus, {**f, "sort": "order"})
    if not lines:
        raise ValueError("Nothing matches the current filters.")
    raw = (dest or "").strip().strip('"')
    if not raw or not os.path.isabs(raw):
        raise ValueError("Enter the full path of the folder to export into.")
    out_dir = os.path.join(os.path.normpath(raw), slug(name, "fish-dataset"))
    if os.path.exists(out_dir) and os.listdir(out_dir):
        raise ValueError("That export folder already has files. Choose a new name or folder.")
    os.makedirs(out_dir, exist_ok=True)

    names: dict[str, str] = {}
    for sp in corpus.speakers():
        base = slug(sp["name"])
        while base in names.values():
            base = f"{base}_{sp['voice_id'][:4]}"
        names[sp["voice_id"]] = base
    counters: collections.Counter = collections.Counter()
    rows: list[dict] = []
    csv_rows: dict[str, list[list[str]]] = collections.defaultdict(list)
    seconds = 0.0
    levels = LevelReport(loudness_db) if loudness_db is not None else None
    omni_rows: list[tuple[bool, dict]] = []
    portable_rows: list[tuple[bool, dict]] = []  # same rows, audio paths relative to the export folder
    for line in lines:
        speaker = names[line["voice_id"]]
        counters[speaker] += 1
        clip_id = f"{speaker}_{counters[speaker]:05d}"
        folder = os.path.join(out_dir, speaker)
        os.makedirs(folder, exist_ok=True)
        src = os.path.join(corpus.root, line["file"])
        target = os.path.join(folder, clip_id + ".wav")
        duration = line["duration_s"]
        rate = line["sample_rate"]
        if omni or loudness_db is not None or (sample_rate and sample_rate != line["sample_rate"]):
            data, src_rate = sf.read(src, dtype="float32", always_2d=True)
            out_rate = sample_rate or src_rate
            mono = resample_mono(data, src_rate, out_rate)
            if loudness_db is not None:
                mono, info = apply_loudness(mono, loudness_db)
                levels.add(line["chapter"], info)
            sf.write(target, np.clip(mono, -1.0, 1.0), out_rate, subtype="PCM_16")
            rate, duration = out_rate, len(mono) / out_rate
        else:
            shutil.copyfile(src, target)
        text = strip_tags(line["text"], kept) if text_mode == "strip" else line["text"].strip()
        seconds += duration
        rows.append({
            "file_name": f"{speaker}/{clip_id}.wav", "text": text, "text_raw": line["text"].strip(),
            "text_plain": line["plain"], "speaker": speaker, "speaker_name": line["voice_name"],
            "voice_id": line["voice_id"], "duration": round(duration, 3), "sample_rate": rate,
            "tags": line["tags"], "chapter": line["chapter"], "run_id": line["run_id"],
            "validation": _in_validation(line["sha256"] or clip_id, val_fraction),
        })
        if omni:
            omni_rows.append((rows[-1]["validation"], {"id": clip_id, "audio_path": os.path.abspath(target),
                                                       "text": text, "language_id": language_id}))
            portable_rows.append((rows[-1]["validation"], {
                "id": clip_id, "audio_path": os.path.relpath(target, out_dir).replace(os.sep, "/"),
                "text": text, "language_id": language_id}))
        if "fish_lab" in formats:
            with open(os.path.join(folder, clip_id + ".lab"), "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text + "\n")
        csv_rows[speaker].append([clip_id, text.replace("|", " "), line["plain"].replace("|", " ")])

    if "jsonl" in formats:
        def write(path: str, subset: list[dict]) -> None:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                for row in subset:
                    fh.write(json.dumps({k: v for k, v in row.items() if k != "validation"}, ensure_ascii=False) + "\n")

        write(os.path.join(out_dir, "metadata.jsonl"), rows)
        if val_fraction > 0:
            write(os.path.join(out_dir, "train.jsonl"), [r for r in rows if not r["validation"]])
            write(os.path.join(out_dir, "val.jsonl"), [r for r in rows if r["validation"]])
    if omni:
        def write_omni(path: str, subset: list[dict]) -> None:
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                for row in subset:
                    fh.write(json.dumps(row, ensure_ascii=False) + "\n")

        write_omni(os.path.join(out_dir, "omnivoice_train.jsonl"), [r for v, r in omni_rows if not v])
        write_omni(os.path.join(out_dir, "omnivoice_train.relative.jsonl"), [r for v, r in portable_rows if not v])
        if val_fraction > 0:
            write_omni(os.path.join(out_dir, "omnivoice_val.jsonl"), [r for v, r in omni_rows if v])
            write_omni(os.path.join(out_dir, "omnivoice_val.relative.jsonl"), [r for v, r in portable_rows if v])
    if "ljspeech" in formats:
        for speaker, items in csv_rows.items():
            with open(os.path.join(out_dir, speaker, "metadata.csv"), "w", encoding="utf-8", newline="") as fh:
                csv.writer(fh, delimiter="|", quoting=csv.QUOTE_NONE, escapechar="\\").writerows(items)
    per_speaker = {s: {"clips": c, "seconds": round(sum(r["duration"] for r in rows if r["speaker"] == s), 1)}
                   for s, c in counters.items()}
    card = {
        "name": name, "clips": len(rows), "hours": round(seconds / 3600, 3), "speakers": per_speaker,
        "formats": formats, "text_mode": text_mode, "kept_tags": kept if text_mode == "strip" else {}, "sample_rate": sample_rate or "as rendered",
        "val_fraction": val_fraction,
        "loudness": levels.summary() if levels else None,
        "language_id": language_id if omni else None, "source_root": corpus.root,
        "source": "Synthetic speech generated by Fish Audio (models: "
                  + ", ".join(sorted({l["model"] or "unknown" for l in lines}))
                  + "). Check Fish's terms before using it to train another model.",
        "filters": {k: v for k, v in f.items() if k != "exclude_keys"} | {"excluded": len(f.get("exclude_keys") or [])},
    }
    if train_options is not None:
        train_seconds = sum(r["duration"] for r in rows if not r["validation"])
        card["training"] = training_bundle.write_bundle(
            out_dir, train_options, name=os.path.basename(out_dir), has_val=val_fraction > 0,
            train_clips=sum(1 for r in rows if not r["validation"]), train_seconds=train_seconds,
            language_id=language_id, speakers=list(per_speaker))
    with open(os.path.join(out_dir, "dataset.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(card, fh, ensure_ascii=False, indent=2)
    return {**card, "path": out_dir}
