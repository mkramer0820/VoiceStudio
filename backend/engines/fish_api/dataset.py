"""Fish story renders read back as a speech-training corpus.

Everything here reads the run folders the story board already wrote
(``<root>/<chapter>/<story>/run-NNN_<time>_<id>/manifest.json`` + ``story.json`` + the audio)
and, on an explicit export, writes a new folder. Nothing contacts Fish or any network.

The corpus is *synthetic* speech: every clip was generated by Fish Audio. Whether it may be
used to train another model is governed by Fish's terms, not by this app; the export card
records the source so that can be checked later.
"""
