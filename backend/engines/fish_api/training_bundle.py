"""A portable training bundle written next to an ``omnivoice`` dataset export.

Training will often run somewhere else (Google Colab, a rented GPU), so the export can carry
everything that run needs: the training config, the data config, a script with the exact commands,
and a short guide. Nothing here runs training or touches the network; it only writes files into the
folder the export just created. Paths in the bundle are relative to that folder, so it works after
the folder is uploaded or moved.
"""
from __future__ import annotations

import dataclasses
import json
import math
import os
import re
import subprocess
from typing import Optional

from . import training

FRAME_RATE_ASSUMED = 25.0  # audio tokenizer frames per second: assumed, not read from the tokenizer
TEXT_OVERHEAD = 1.15  # text tokens and padding on top of the audio frames
ESTIMATE_NOTE = (
    f"Estimated, not measured: assumes the audio tokenizer runs at {FRAME_RATE_ASSUMED:g} frames per second "
    f"and about {round((TEXT_OVERHEAD - 1) * 100)}% extra positions for text. The real number comes from "
    "the tokenised data after step 1."
)
UPSTREAM_URL = "https://github.com/debpalash/VoiceStudio.git"

CONFIG_FILES = ("train_config.json", "data_config.json", "train.sh", "COLAB.md")


def options_from(spec: Optional[dict]) -> training.TrainOptions:
    """Validated training options; unknown or out-of-range values raise ``ValueError``."""
    data = dict(spec or {})
    for local_only in ("python", "allow_download"):  # a bundle runs elsewhere: never carry local paths
        data.pop(local_only, None)
    opts = training.TrainOptions.from_dict(data)
    if opts.mode == "full" and "learning_rate" not in data:
        opts.learning_rate = 5e-5  # the repo's fine-tuning template, not the LoRA default
    return opts


def tokens_per_pass(seconds: float) -> float:
    return max(1.0, seconds * FRAME_RATE_ASSUMED * TEXT_OVERHEAD)


def estimate(seconds: float, steps: int, batch_tokens: int) -> dict:
    """How many times the training clips are seen by ``steps`` (a rough guide)."""
    per_pass = tokens_per_pass(seconds)
    return {"steps_per_pass": round(per_pass / batch_tokens, 1),
            "passes": round(steps * batch_tokens / per_pass, 1), "note": ESTIMATE_NOTE}


def suggest_steps(seconds: float, batch_tokens: int, passes: float) -> int:
    """Steps that give about ``passes`` passes over the data, within the allowed range."""
    low, high = training.TrainOptions._RANGES["steps"]
    return int(min(high, max(low, math.ceil(passes * tokens_per_pass(seconds) / batch_tokens))))


def _git(*args: str) -> Optional[str]:
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    try:
        out = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 and out.stdout.strip() else None


def repo_info() -> dict:
    """Where a fresh machine can fetch this code (it holds the LoRA trainer): this checkout's remote and branch."""
    url = _git("remote", "get-url", "origin") or UPSTREAM_URL
    ssh = re.fullmatch(r"git@([^:]+):(.+)", url)
    if ssh:
        url = f"https://{ssh.group(1)}/{ssh.group(2)}"
    url = re.sub(r"^(https?://)[^/@]+@", r"\1", url)  # never write credentials into a script
    ref = _git("rev-parse", "--abbrev-ref", "HEAD")
    return {"url": url, "ref": ref if ref and ref != "HEAD" else "main"}


def _slash(argv: list[str]) -> str:
    import shlex

    return " ".join(shlex.quote(a.replace("\\", "/")) for a in argv)


def train_script(opts: training.TrainOptions, *, has_val: bool, repo: dict) -> str:
    local = dataclasses.replace(opts, python="python3")
    cmds = training.build_commands(
        ".", local, train_jsonl="omnivoice_train.relative.jsonl",
        val_jsonl="omnivoice_val.relative.jsonl" if has_val else None)
    tokenize = "\n".join(_slash(cmds[k]) for k in ("tokenize_train", "tokenize_dev") if k in cmds)
    train = _slash(["python3", "-m", "accelerate.commands.launch", "--num_processes", "1", "--num_machines", "1",
                    "-m", "omnivoice.cli.train", "--train_config", "train_config.json",
                    "--data_config", "data_config.json", "--output_dir", "output"])
    return f"""#!/usr/bin/env bash
# Generated by VoiceStudio. Usage: bash train.sh [setup|tokenize|train|all]   (default: all)
# Read COLAB.md first. This script has not been run on Colab by the generator.
set -euo pipefail
cd "$(dirname "${{BASH_SOURCE[0]}}")"
HERE="$(pwd)"

# The trainer (including the LoRA code) lives in the VoiceStudio repository.
REPO_URL="${{REPO_URL:-{repo['url']}}}"
REPO_REF="${{REPO_REF:-{repo['ref']}}}"
if [ -d /content ]; then REPO_DIR="${{REPO_DIR:-/content/VoiceStudio-src}}"; else REPO_DIR="${{REPO_DIR:-$HERE/../VoiceStudio-src}}"; fi

stage="${{1:-all}}"

setup() {{
  if [ ! -d "$REPO_DIR/omnivoice" ]; then
    git clone --depth 1 --branch "$REPO_REF" "$REPO_URL" "$REPO_DIR"
  fi
  pip install -q accelerate webdataset tensorboard soundfile safetensors transformers
  export PYTHONPATH="$REPO_DIR:${{PYTHONPATH:-}}"
}}

tokenize() {{
  export PYTHONPATH="$REPO_DIR:${{PYTHONPATH:-}}"
{chr(10).join('  ' + line for line in tokenize.splitlines())}
}}

train() {{
  export PYTHONPATH="$REPO_DIR:${{PYTHONPATH:-}}"
  {train}
}}

case "$stage" in
  setup) setup ;;
  tokenize) tokenize ;;
  train) train ;;
  all) setup; tokenize; train ;;
  *) echo "usage: bash train.sh [setup|tokenize|train|all]"; exit 2 ;;
esac
"""


def colab_guide(opts: training.TrainOptions, *, name: str, repo: dict, train_clips: int, train_seconds: float,
                has_val: bool, language_id: str, speakers: list[str]) -> str:
    est = estimate(train_seconds, opts.steps, opts.batch_tokens)
    mins = train_seconds / 60
    full = opts.mode == "full"
    return f"""# Training guide: {name}

Everything needed to train on another machine (for example Google Colab) is in this folder. It was generated by
VoiceStudio and has **not been run on Colab by the generator**: treat the first run as a test.

## What is in this folder

| File | Purpose |
|---|---|
| `omnivoice_train.relative.jsonl`{' / `omnivoice_val.relative.jsonl`' if has_val else ''} | the clips: `id`, `audio_path` (relative to this folder), `text`, `language_id` (`{language_id}`) |
| `{'`, `'.join(speakers)}/` | the 24 kHz mono WAVs |
| `train_config.json` | the trainer settings (see the table below) |
| `data_config.json` | where the tokenised data will be (`tokens/`) |
| `train.sh` | the exact commands: `setup`, `tokenize`, `train` |
| `omnivoice_*.jsonl` (without `.relative`) | the same rows with absolute paths on the machine that exported them; ignore elsewhere |
| `dataset.json` | the export card: filters, tags, loudness, source |

Training clips: **{train_clips}** ({mins:.0f} min){', plus a held-out validation set' if has_val else ', no validation set'}.

## Run it

1. Upload this whole folder (about the size of the WAVs) to Colab or to Google Drive and mount Drive, or zip it first.
2. Use a **GPU** runtime. In a Colab cell:

```
%cd /content/{name}   # or the Drive path where you put the folder
!bash train.sh setup
!bash train.sh tokenize
!bash train.sh train
```

`setup` clones `{repo['url']}` at `{repo['ref']}` (that is where the trainer and its LoRA code live) and installs
`accelerate webdataset tensorboard soundfile safetensors transformers`. If the clone fails (private repository, a branch
that was not pushed), set `REPO_URL` and `REPO_REF` before running. `tokenize` downloads
`{opts.tokenizer_path}` and `train` downloads the base model `{opts.base_checkpoint}`, so the runtime needs internet.
3. Checkpoints appear in `output/checkpoint-<step>/`{' (the LoRA adapter is in `adapter/` inside each)' if not full else ''}.
Copy the last one back to your computer; Drive keeps it if the runtime disconnects. Resume by setting
`resume_from_checkpoint` in `train_config.json` to a checkpoint folder and running `bash train.sh train` again.

## Settings in `train_config.json`

| Setting | Value |
|---|---|
| mode | {'**LoRA adapter** (`lora_enabled: true`), rank ' + str(opts.lora_r) + ', alpha ' + str(opts.lora_alpha) + ', dropout ' + str(opts.lora_dropout) if not full else '**full fine-tune** (`lora_enabled: false`): needs far more GPU memory'} |
| base model | `{opts.base_checkpoint}` |
| steps | {opts.steps} |
| learning rate | {opts.learning_rate:g} ({opts.lr_scheduler_type}, warm-up {opts.warmup_ratio:g}) |
| tokens per batch | {opts.batch_tokens} (accumulation {opts.gradient_accumulation_steps}) |
| precision | {opts.mixed_precision} |
| checkpoint / evaluation every | {opts.save_every or max(50, opts.steps // 5)} / {opts.eval_every or opts.save_every or max(50, opts.steps // 5)} steps, keeping {opts.keep_last_n_checkpoints if opts.keep_last_n_checkpoints >= 0 else 'all'} |
| seed | {opts.seed} |

**How long is that?** About {est['steps_per_pass']:g} steps per pass over the training clips, so {opts.steps} steps is about
**{est['passes']:g} passes**. {est['note']} Small voices overfit quickly: watch the evaluation loss in
`output/` (TensorBoard) and keep the checkpoint where it stops improving, not the last one.

## Notes

- The exported config uses the in-repo LoRA fields (`lora_*`). If you train with another library such as `peft`
  instead, keep the clips, base model and the hyper-parameters above and translate the LoRA settings.
- The audio is synthetic speech generated by Fish Audio. Check their terms before training on it.
- Flex attention in the trainer needs Triton, which Colab's Linux GPU runtimes normally have.
"""


def write_bundle(out_dir: str, opts: training.TrainOptions, *, name: str, has_val: bool, train_clips: int,
                 train_seconds: float, language_id: str, speakers: list[str]) -> dict:
    """Write the config files into ``out_dir`` and return a summary for the export card."""
    repo = repo_info()
    train_cfg = training.build_train_config(opts, has_val=has_val)
    train_cfg["num_workers"] = opts.num_workers
    data_cfg = {"train": [{"manifest_path": ["tokens/train/data.lst"]}]}
    if has_val:
        data_cfg["dev"] = [{"manifest_path": ["tokens/dev/data.lst"]}]
    files = {
        "train_config.json": json.dumps(train_cfg, indent=2) + "\n",
        "data_config.json": json.dumps(data_cfg, indent=2) + "\n",
        "train.sh": train_script(opts, has_val=has_val, repo=repo),
        "COLAB.md": colab_guide(opts, name=name, repo=repo, train_clips=train_clips, train_seconds=train_seconds,
                                has_val=has_val, language_id=language_id, speakers=speakers),
    }
    for fname, text in files.items():
        with open(os.path.join(out_dir, fname), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    options = dataclasses.asdict(opts)
    options.pop("python", None)
    return {"files": list(CONFIG_FILES), "options": options, "repo": repo,
            "estimate": estimate(train_seconds, opts.steps, opts.batch_tokens)}
